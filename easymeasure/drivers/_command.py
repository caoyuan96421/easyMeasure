def class_name(driver_name: str) -> str:
    return "".join(p.capitalize() or "_" for p in driver_name.split("_")) or "Driver"


def render_source(definition: dict) -> str:
    """The Python file of a wizard driver."""
    d = _filled(definition)
    body = pprint.pformat(d, indent=1, width=96, sort_dicts=False)
    desc = (d["description"] or d["name"]).replace('"""', "'''")
    return '''%s
"""%s

Made with the Driver Wizard.  Reopen it there to change it, or edit DEFINITION here
(see easymeasure/drivers/_command.py for the format).  The class may also be
extended by hand, e.g. by overriding read() / write() for special channels.
"""

from easymeasure.drivers._command import CommandInstrument

DEFINITION = %s


class %s(CommandInstrument):
    DEFINITION = DEFINITION


DRIVER = %s
''' % (GENERATED_MARK, desc, body, class_name(d["name"]), class_name(d["name"]))


def read_definition(path: Path) -> dict:
    """The DEFINITION of a wizard driver file (without importing it)."""
    tree = ast.parse(Path(path).read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "DEFINITION" for t in node.targets):
            return ast.literal_eval(node.value)
    raise DriverError("%s has no DEFINITION (not made with the Driver Wizard)" % path)


def is_wizard_file(path: Path) -> bool:
    try:
        return Path(path).read_text(encoding="utf-8").startswith(GENERATED_MARK)
    except OSError:
        return False


