NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
DRIVER_NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
_NUM_RE = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[Ee][+-]?\d+)?|[+-]?(?:inf|nan)", re.I)
_BOOL_WORDS = {"ON": "1", "OFF": "0", "TRUE": "1", "FALSE": "0"}
GENERATED_MARK = "# generated by the easyMeasure Driver Wizard"


