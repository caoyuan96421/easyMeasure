class CommandInstrument(SCPIInstrument):
    """An instrument made from a definition (see the module doc)."""

    DEFINITION: dict = {}

    def __init_subclass__(cls, **kw):
        super().__init_subclass__(**kw)
        if cls.DEFINITION:
            cls._build(cls.DEFINITION)

    @classmethod
    def _build(cls, definition: dict) -> None:
        d = normalize_definition(definition)
        cls.DEF = d
        cls.DESCRIPTION = d["description"] or "%s (Driver Wizard)" % d["name"]
        cls.IDN_MATCH = tuple(m.strip() for m in d["idn_match"].split("|") if m.strip())
        opts = dict(SCPIInstrument.DEFAULT_OPTIONS)
        opts.update(d["options"])
        opts["check_errors"] = bool(d["error_query"]) and opts.get("check_errors", True)
        cls.DEFAULT_OPTIONS = opts
        cls.CHANNELS = [cls._spec(c) for c in d["channels"]]
        cls.ACTIONS = [ActionSpec(a["name"], a["description"] or "; ".join(a["commands"]))
                       for a in d["actions"]]
        cls._chan = {c["name"]: c for c in d["channels"]}
        cls._act = {a["name"]: a for a in d["actions"]}

    @classmethod
    def from_definition(cls, definition: dict) -> type:
        """A driver class for *definition* (used by the wizard's "try it")."""
        return type("Wizard_" + str(definition.get("name", "driver")), (cls,),
                    {"DEFINITION": definition})

    @staticmethod
    def _spec(c: dict) -> ChannelSpec:
        vector = c["dtype"] == "vector"
        allowed = c["allowed"]
        if allowed is not None and c["dtype"] == "float":
            allowed = [float(a) for a in allowed]
        return ChannelSpec(c["name"], c["access"], "float" if vector else c["dtype"],
                           (-1,) if vector else (), c["unit"], c["description"],
                           timeout=float(c["timeout"]) if c["timeout"] else None,
                           config=bool(c["config"]), allowed=allowed)

    def q(self, cmd: str) -> str:
        """A query, waiting ``query_delay`` seconds before reading (slow instruments)."""
        return self.resource.query(cmd, float(self.options.get("query_delay") or 0.0)).strip()

    # -- connection -------------------------------------------------------------
    def connect(self):
        d = self.DEF
        self.select(self.resource)
        if d["idn_query"]:
            idn = self.q(d["idn_query"])
            if self.IDN_MATCH and not any(m.upper() in idn.upper() for m in self.IDN_MATCH):
                raise IOError("%s: unexpected instrument %r (expected %s)"
                              % (d["name"], idn[:80], " / ".join(self.IDN_MATCH)))
            self.idn = idn
        if d["error_query"] and self.options.get("check_errors", True):
            self.read_errors()                    # start with an empty error queue
        for cmd in d["init"]["commands"]:
            self._send(cmd, "init")
        if d["init"]["script"].strip():
            self._run_script(d["init"]["script"])
        if d["error_query"] and self.options.get("check_errors", True):
            errs = self.read_errors()
            if errs:
                raise IOError("the instrument reported errors during initialization: %s"
                              % "; ".join(errs))

    def disconnect(self):
        for cmd in self.DEF["shutdown"]["commands"]:
            try:
                self._send(cmd, "shutdown")
            except Exception as exc:
                log.warning("%s: shutdown command %r failed: %s", self.name, cmd, exc)

    def _send(self, cmd: str, what: str) -> Optional[str]:
        cmd = cmd.strip()
        if not cmd or cmd.startswith("#"):
            return None
        if cmd.endswith("?"):
            r = self.q(cmd)
            log.info("%s %s: %s -> %s", self.name, what, cmd, r[:120])
            return r
        self.w(cmd)
        return None

    def _run_script(self, code: str) -> None:
        ns = {"write": self.w, "query": self.q, "read": self.resource.read,
              "sleep": time.sleep, "log": lambda m: log.info("%s init: %s", self.name, m),
              "options": dict(self.options), "instrument": self, "np": np, "math": math,
              "__builtins__": __builtins__}
        try:
            exec(compile(code, "<%s init script>" % self.DEF["name"], "exec"), ns)
        except (IOError, OSError):
            raise
        except Exception as exc:
            raise IOError("init script: %s: %s" % (type(exc).__name__, exc)) from None

    def read_errors(self) -> List[str]:
        q = self.DEF["error_query"]
        out = []
        for _ in range(20):
            r = self.q(q)
            m = _NUM_RE.search(r)
            if m is None:
                raise IOError("bad error-queue reply %r" % r[:60])
            if float(m.group(0)) == 0:
                break
            out.append(r.strip())
        return out

    # -- channel I/O ---------------------------------------------------------
    def read(self, channel):
        c = self._chan.get(channel)
        if c is None or "r" not in c["access"]:
            raise ChannelError("%s: channel %s is not readable" % (self.name, channel))
        reply = self.q(c["get"])
        if c["dtype"] == "str":
            return self._from_word(c, reply)
        scale = float(c["scale"]) if c["scale"] else 1.0
        if c["dtype"] == "vector":
            vals = [to_float(p) for p in reply.replace(";", ",").split(",") if p.strip()]
            return np.asarray(vals, dtype=float) * scale
        m = _NUM_RE.search(reply)
        if m is None:
            raise IOError("%s: no number in the reply %r" % (channel, reply[:60]))
        return to_float(m.group(0)) * scale

    def write(self, channel, value):
        c = self._chan.get(channel)
        if c is None or "w" not in c["access"]:
            raise ChannelError("%s: channel %s is not writable" % (self.name, channel))
        if c["dtype"] == "str":
            v: Any = (c["map"] or {}).get(value, value)
        else:
            v = float(value) / (float(c["scale"]) if c["scale"] else 1.0)
        cmd = c["set"]
        if "{value}" in cmd and not isinstance(v, str):
            cmd = cmd.replace("{value}", fmt(v))      # enough digits, no locale surprises
        cmd = cmd.format(value=v)
        if self.options.get("check_errors", True) and self.DEF["error_query"]:
            self.checked(cmd)
        else:
            self.w(cmd)

    @staticmethod
    def _from_word(c: dict, reply: str) -> str:
        """Instrument reply -> channel value (through the map, SCPI-tolerant)."""
        r = reply.strip().strip('"').strip("'").strip()
        # without a map the allowed values are their own instrument words
        mp = c["map"] or {str(a): str(a) for a in (c["allowed"] or [])}
        if not mp:
            return r
        key = r.upper()
        for value, word in mp.items():
            w = word.strip().strip('"').upper()
            if key == w or key == _BOOL_WORDS.get(w, "\0") or w == _BOOL_WORDS.get(key, "\0"):
                return value
            # SCPI: the reply may be the short form of the word we sent (VOLT for VOLTAGE)
            # or carry a default suffix (VOLT for VOLT:DC)
            if len(key) >= 3 and (w.startswith(key) or key.startswith(w)):
                return value
        for value in mp:                              # the reply is the value itself
            if key == value.upper():
                return value
        return r

    # -- actions ------------------------------------------------------------
    def action(self, name):
        a = self._act.get(name)
        if a is None:
            raise ChannelError("%s has no action %s" % (self.name, name))
        for cmd in a["commands"]:
            self._send(cmd, "action " + name)


