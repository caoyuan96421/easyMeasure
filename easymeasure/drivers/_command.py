"""Command-based instruments described by data: the engine behind the Driver Wizard.

A *definition* (a plain dict, JSON-compatible) describes an instrument that is
controlled by text commands - most SCPI instruments, and many older ones:

.. code-block:: python

    {"name": "my_meter", "description": "...",
     "idn_query": "*IDN?", "idn_match": "34461",       # identification (optional)
     "options": {"timeout": 5.0, "read_termination": "\\n", "write_termination": "\\n"},
     "error_query": "SYST:ERR?",                       # read after every setting
     "init": {"commands": ["*CLS"], "script": "..."},  # run on connect
     "shutdown": {"commands": []},                     # run on disconnect (best effort)
     "channels": [
        {"name": "volt", "access": "r", "dtype": "float", "unit": "V",
         "get": "READ?"},
        {"name": "func", "access": "rw", "dtype": "str", "config": True,
         "get": "FUNC?", "set": 'FUNC "{value}"',
         "allowed": ["DC V", "AC V"], "map": {"DC V": "VOLT:DC", "AC V": "VOLT:AC"}}],
     "actions": [{"name": "reset", "commands": ["*RST"], "description": "..."}]}

Channels
    ``access`` r / w / rw; ``dtype`` float, str or vector (comma-separated
    numbers, read-only); ``config`` marks a setting.  ``get`` is the query whose
    reply is the value (numbers: the first number in the reply; text: the reply
    without quotes), ``set`` the command with ``{value}`` (or ``{value:.3f}``) where
    the value goes.  ``allowed`` lists accepted values (drop-down in the front
    ends); ``map`` translates a value into the instrument's word (``"Voltage":
    "VOLT"``) and back - replies are recognised in SCPI short or long form, and
    ``1``/``0`` match ``ON``/``OFF``.  ``scale`` multiplies readings and divides
    settings (instrument in mA, channel in A: ``scale`` 0.001).  ``timeout``
    overrides the call deadline.

Initialization
    ``init.commands`` are sent in order on connect (a command ending in ``?`` is a
    query; its reply is logged).  ``init.script`` is Python run afterwards with
    ``write(cmd)``, ``query(cmd)``, ``read()``, ``sleep(s)``, ``log(msg)``,
    ``options``, ``instrument`` and ``np``/``math``; raise an exception to refuse the
    connection (e.g. a wrong model).

Driver files generated by the wizard (``<home>/drivers/<name>.py``) hold the
definition as a Python literal plus a class; the class may be extended by hand
(override ``read`` / ``write`` for special channels), and the wizard reopens the
file through its ``DEFINITION``.
"""

