def normalize_definition(d: dict) -> dict:
    """Fill defaults and check a definition; raises DriverError listing every problem."""
    errors, _ = check_definition(d)
    if errors:
        raise DriverError("driver definition: " + "; ".join(errors))
    return _filled(d)


def _filled(d: dict) -> dict:
    out = copy.deepcopy(d)
    out.setdefault("description", "")
    out.setdefault("idn_query", "")
    out.setdefault("idn_match", "")
    out.setdefault("error_query", "")
    out.setdefault("options", {})
    out.setdefault("init", {})
    out["init"].setdefault("commands", [])
    out["init"].setdefault("script", "")
    out.setdefault("shutdown", {})
    out["shutdown"].setdefault("commands", [])
    out.setdefault("channels", [])
    out.setdefault("actions", [])
    for c in out["channels"]:
        c.setdefault("access", "r")
        c.setdefault("dtype", "float")
        c.setdefault("unit", "")
        c.setdefault("description", "")
        c.setdefault("config", False)
        c.setdefault("get", "")
        c.setdefault("set", "")
        c.setdefault("allowed", None)
        c.setdefault("map", None)
        c.setdefault("scale", None)
        c.setdefault("timeout", None)
        if c["map"] and not c["allowed"]:
            c["allowed"] = list(c["map"])
    for a in out["actions"]:
        a.setdefault("description", "")
        a.setdefault("commands", [])
        if isinstance(a["commands"], str):
            a["commands"] = [x for x in a["commands"].splitlines() if x.strip()]
    return out


def check_definition(d: Any, builtin_names=()) -> tuple:
    """(errors, warnings) of a definition, as lists of human-readable strings."""
    errors: List[str] = []
    warnings: List[str] = []
    if not isinstance(d, dict):
        return ["the definition must be a dict"], warnings
    name = d.get("name", "")
    if not isinstance(name, str) or not DRIVER_NAME_RE.match(name or ""):
        errors.append("driver name %r: use lower-case letters, digits and _ (start with a "
                      "letter)" % (name,))
    elif keyword.iskeyword(name) or name in builtin_names:
        errors.append("driver name %r is taken by a built-in driver" % name)
    for key in ("description", "idn_query", "idn_match", "error_query"):
        if not isinstance(d.get(key, ""), str):
            errors.append("%s must be text" % key)
    opts = d.get("options", {})
    if not isinstance(opts, dict):
        errors.append("options must be a dict")
    for part in ("init", "shutdown"):
        p = d.get(part, {})
        if not isinstance(p, dict):
            errors.append("%s must be a dict" % part)
            continue
        cmds = p.get("commands", [])
        if not isinstance(cmds, list) or not all(isinstance(c, str) for c in cmds):
            errors.append("%s commands must be a list of text lines" % part)
    script = (d.get("init") or {}).get("script", "") if isinstance(d.get("init"), dict) else ""
    if script:
        if not isinstance(script, str):
            errors.append("init script must be text")
        else:
            try:
                compile(script, "<init script>", "exec")
            except SyntaxError as exc:
                errors.append("init script: syntax error line %s: %s" % (exc.lineno, exc.msg))
    chans = d.get("channels", [])
    if not isinstance(chans, list):
        errors.append("channels must be a list")
        chans = []
    seen = set()
    for k, c in enumerate(chans):
        where = "channel %d" % (k + 1)
        if not isinstance(c, dict):
            errors.append("%s must be a dict" % where)
            continue
        n = c.get("name", "")
        if not isinstance(n, str) or not NAME_RE.match(n or ""):
            errors.append("%s: name %r must be letters, digits, _ (start with a letter)" % (where, n))
            continue
        where = "channel %s" % n
        if n in seen:
            errors.append("%s: duplicate name" % where)
        seen.add(n)
        acc = c.get("access", "r")
        dt = c.get("dtype", "float")
        if acc not in ("r", "w", "rw"):
            errors.append("%s: access must be r, w or rw" % where)
            continue
        if dt not in ("float", "str", "vector"):
            errors.append("%s: type must be float, str or vector" % where)
            continue
        get, set_ = c.get("get", "") or "", c.get("set", "") or ""
        if not isinstance(get, str) or not isinstance(set_, str):
            errors.append("%s: get / set must be text" % where)
            continue
        if "r" in acc and not get.strip():
            errors.append("%s: readable, so it needs a get (query) command" % where)
        if "w" in acc and not set_.strip():
            errors.append("%s: writable, so it needs a set command" % where)
        if "w" in acc and set_.strip():
            if "{value" not in set_:
                errors.append("%s: the set command needs {value} where the value goes" % where)
            else:
                try:
                    set_.format(value=1.0 if dt == "float" else "X")
                except (ValueError, KeyError, IndexError) as exc:
                    errors.append("%s: set command %r: %s" % (where, set_, exc))
        if dt == "vector" and "w" in acc:
            errors.append("%s: vectors can only be read" % where)
        if "r" in acc and get.strip() and not get.strip().endswith("?"):
            warnings.append("%s: the get command %r does not end in '?' - is it a query?"
                            % (where, get))
        allowed, mp = c.get("allowed"), c.get("map")
        if allowed is not None:
            if not isinstance(allowed, list) or not allowed:
                errors.append("%s: allowed values must be a non-empty list" % where)
            elif dt == "float":
                try:
                    [float(a) for a in allowed]
                except (TypeError, ValueError):
                    errors.append("%s: allowed values of a number channel must be numbers" % where)
            elif dt == "vector":
                errors.append("%s: a vector cannot have allowed values" % where)
        if mp is not None:
            if not isinstance(mp, dict) or not all(isinstance(v, str) for v in mp.values()):
                errors.append("%s: map must be {value: instrument word}" % where)
            elif dt != "str":
                errors.append("%s: only text channels can have a map" % where)
            elif allowed and set(mp) - set(allowed):
                errors.append("%s: mapped values %s are not among the allowed values"
                              % (where, ", ".join(sorted(set(mp) - set(allowed)))))
        sc = c.get("scale")
        if sc is not None:
            try:
                if float(sc) == 0:
                    raise ValueError
            except (TypeError, ValueError):
                errors.append("%s: scale must be a non-zero number" % where)
            if dt == "str":
                errors.append("%s: text channels cannot be scaled" % where)
        to = c.get("timeout")
        if to is not None:
            try:
                if float(to) <= 0:
                    raise ValueError
            except (TypeError, ValueError):
                errors.append("%s: timeout must be a positive number of seconds" % where)
    acts = d.get("actions", [])
    if not isinstance(acts, list):
        errors.append("actions must be a list")
        acts = []
    aseen = set()
    for k, a in enumerate(acts):
        if not isinstance(a, dict) or not NAME_RE.match(str(a.get("name", ""))):
            errors.append("action %d: needs a name (letters, digits, _)" % (k + 1))
            continue
        if a["name"] in aseen:
            errors.append("action %s: duplicate name" % a["name"])
        aseen.add(a["name"])
        cmds = a.get("commands", [])
        if isinstance(cmds, str):
            cmds = [x for x in cmds.splitlines() if x.strip()]
        if not isinstance(cmds, list) or not cmds or not all(isinstance(x, str) for x in cmds):
            errors.append("action %s: needs at least one command" % a["name"])
    if not chans and not acts:
        warnings.append("the driver has neither channels nor actions")
    return errors, warnings


