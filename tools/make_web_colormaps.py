"""Regenerate easymeasure/remote/web/js/colormaps.js from the GUI's colormaps."""
import base64, os, sys
import numpy as np
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from easymeasure.frontend.plotting import colormaps

out = ["// generated by tools/make_web_colormaps.py - 256-entry RGB tables (base64)",
       "const RAW = {"]
for name in colormaps.available():
    cm = colormaps.get(name)
    lut = cm.getLookupTable(0.0, 1.0, 256, alpha=False).astype(np.uint8)
    out.append('  %r: "%s",' % (name, base64.b64encode(lut.tobytes()).decode()))
out.append("};")
out.append('''
const cache = {};
export const NAMES = Object.keys(RAW);
/** Uint8Array(256*3) RGB lookup table */
export function lut(name) {
  if (!(name in RAW)) name = "viridis";
  if (!cache[name]) {
    const s = atob(RAW[name]);
    const a = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) a[i] = s.charCodeAt(i);
    cache[name] = a;
  }
  return cache[name];
}
/** CSS colour for position t in [0, 1] */
export function color(name, t) {
  const l = lut(name);
  const i = Math.max(0, Math.min(255, Math.round(t * 255))) * 3;
  return `rgb(${l[i]},${l[i + 1]},${l[i + 2]})`;
}
''')
path = os.path.join(os.path.dirname(__file__), "..", "easymeasure", "remote", "web", "js", "colormaps.js")
open(path, "w").write("\n".join(out))
print("wrote", path)
